"""Render the raw puck-slide recording in ``examples/raw/puck_slide`` (CC0).

    python scripts/make_puck_recording.py examples/raw/puck_slide

A red puck launched across a grey floor slides to a stop under Coulomb friction (coefficient
0.237, not published in the recording). Writes the video, the calibrated camera, the
measurements an experimenter would note, and the puck's trajectory for the recorded launch and
three repeated launches at the same setting.
"""

import json
import sys
from pathlib import Path

import numpy as np

from real2simlab.benchmarks.synthetic.physics import render
from real2simlab.benchmarks.synthetic.physics.common import look_at
from real2simlab.media import write_video

FPS, FRAMES, G, MU = 30.0, 60, 9.81, 0.237
HALF = np.array([0.04, 0.04, 0.015])
CASES = {"observed": ((1.2, 0.0), MU)}
OUTCOMES = {
    "observed": "the recorded launch",
    "observed_repeat1..3": "three more launches at the same setting",
}


def slide(v0, mu=MU, x0=(-0.6, 0.0)):
    t = np.arange(FRAMES) / FPS
    v0 = np.asarray(v0, float)
    speed = np.linalg.norm(v0)
    tau = np.minimum(t, speed / (mu * G))
    s = speed * tau - 0.5 * mu * G * tau**2
    xy = np.asarray(x0)[None] + s[:, None] * (v0 / speed)[None]
    return t, np.c_[xy, np.full(FRAMES, HALF[2])]


def main(out: Path) -> None:
    (out / "outcomes").mkdir(parents=True, exist_ok=True)
    camera = look_at((0.0, -1.4, 0.9), (0.0, 0.0, 0.0), fov_deg=55.0, width=480, height=270)
    floor = render.Box(np.array([0, 0, -0.01]), np.eye(3), np.array([1.5, 1.0, 0.01]), (0.55,) * 3)
    _, pos = slide((1.2, 0.0))
    puck = [[render.Box(p, np.eye(3), HALF, (0.85, 0.12, 0.1))] for p in pos]
    write_video(render.render_frames(camera, [floor], puck), out / "observed.mp4", fps=FPS)
    (out / "camera.json").write_text(json.dumps(camera, indent=1) + "\n")
    rng = np.random.default_rng(3)
    for name, (v0, mu) in CASES.items():
        t, p = slide(v0, mu)
        np.savez(out / "outcomes" / f"{name}.npz", t=t, position=p)
        if name == "observed":  # repeated launches: small launch-speed scatter
            for k in range(1, 4):
                t, p = slide(np.asarray(v0) * (1 + rng.normal(0, 0.02)), mu)
                np.savez(out / "outcomes" / f"observed_repeat{k}.npz", t=t, position=p)
    measurements = {
        "puck": {"size_m": [0.08, 0.08, 0.03], "mass_kg": 0.17, "color": "red"},
        "floor": "flat grey surface, z = 0",
        "observed_launch": {
            "velocity_m_s": [1.2, 0.0, 0.0],
            "start_position_m": [-0.6, 0.0, 0.015],
            "how": "launcher, measured by a light gate",
        },
        "frame_rate": FPS,
        "frames": FRAMES,
        "camera": "camera.json: OpenCV axes, camera-to-world extrinsics, calibrated",
        "outcomes": OUTCOMES,
    }
    (out / "measurements.json").write_text(json.dumps(measurements, indent=1) + "\n")
    (out / "README.txt").write_text(
        "Puck slide recordings. Generated by Real2SimLab for testing; CC0-1.0 (public domain).\n"
        "Outcome files: t (N,) seconds, position (N, 3) metres, puck centre, world frame z up.\n"
    )


if __name__ == "__main__":
    main(Path(sys.argv[1]))
