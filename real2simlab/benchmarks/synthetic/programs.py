"""Twin programs built from the synthetic physics: the truth generator and scripted twins.

They are ordinary twin programs: ``run.py``, the ``synthphys`` package (a copy of
``physics/``), a copy of the SDK and a ``model.json``. They run in ``r2s-python`` without
Real2SimLab.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from real2simlab._fs import copy_tree
from real2simlab.twin.sdk import sdk_path

PHYSICS_DIR = Path(__file__).with_name("physics")
PACKAGE = "synthphys"
MODEL_FILE = "model.json"

SIMULATE = '''\
"""A twin of the synthetic "{title}" task, generated by Real2SimLab."""

import json
from pathlib import Path

import r2s_twin

from synthphys import PHENOMENA, render_video_frames

MODEL = json.loads(Path(__file__).with_name("model.json").read_text())
phenomenon = PHENOMENA[MODEL["phenomenon"]]
twin = r2s_twin.Twin()
fps = phenomenon.FPS if hasattr(phenomenon, "FPS") else 30.0
setup = MODEL.get("setup", phenomenon.SETUP)
tracks = phenomenon.simulate(setup, MODEL["params"], fps)
twin.write_tracks(
    fps=fps,
    positions={{name: data["position"] for name, data in tracks.items()}},
    quaternions={{n: d["quaternion"] for n, d in tracks.items() if "quaternion" in d}},
    camera=phenomenon.CAMERA,
)
if MODEL.get("render"):
    twin.write_video(render_video_frames(phenomenon, tracks, setup), fps)
'''


def _common(target: Path, model: dict[str, Any]) -> None:
    target.mkdir(parents=True, exist_ok=True)
    copy_tree(PHYSICS_DIR, target / PACKAGE, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    shutil.copyfile(sdk_path(), target / "r2s_twin.py")
    (target / MODEL_FILE).write_text(json.dumps(model, indent=2) + "\n", encoding="utf-8")


def simulation_program(
    target: Path,
    *,
    phenomenon: str,
    title: str,
    params: dict[str, Any],
    setup: dict[str, Any] | None = None,
    render: bool = False,
) -> Path:
    """A program that simulates ``phenomenon`` with ``params`` from ``setup`` (its initial
    state; by default the evaluation task's)."""
    model: dict[str, Any] = {"phenomenon": phenomenon, "params": params, "render": render}
    if setup is not None:
        model["setup"] = setup
    _common(target, model)
    (target / "run.py").write_text(SIMULATE.format(title=title), encoding="utf-8")
    return target
